const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const assert = require('node:assert/strict');

async function main() {
  const { chromium } = require(path.join(process.argv[2], 'playwright'));
  const { PDFDocument } = require('../frontend/node_modules/pdf-lib');
  const base = 'http://127.0.0.1:5180';
  const api = 'http://127.0.0.1:5104/api/v1';
  const configuration = {};
  for (const file of ['.env', '.env.platform.local']) for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    if (!line.trim() || line.trimStart().startsWith('#')) continue;
    const separator = line.indexOf('='); configuration[line.slice(0, separator)] = line.slice(separator + 1);
  }
  const code = `qa-student-${Date.now()}`;
  const email = `${code}@example.test`;
  const password = require('node:crypto').randomBytes(12).toString('hex');
  const artifacts = path.resolve('.artifacts/student-enrollment', code);
  fs.mkdirSync(artifacts, { recursive: true });
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } });
  page.setDefaultTimeout(30000);
  const pageErrors = []; page.on('pageerror', error => pageErrors.push(error.message));
  const consoleErrors = []; const failedRequests = [];
  page.on('console', message => { if (message.type() === 'error') consoleErrors.push(message.text()); });
  page.on('requestfailed', request => failedRequests.push({ url: request.url(), error: request.failure()?.errorText }));
  const steps = []; let tenantCreated = false;
  async function request(endpoint, token, body, method = 'POST', sede = code) {
    const response = await fetch(api + endpoint, { method, headers: { 'Content-Type': 'application/json', 'X-Sede-Code': sede, ...(token ? { Authorization: `Bearer ${token}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    const text = await response.text();
    const result = text ? JSON.parse(text) : null;
    return { status: response.status, result };
  }
  async function chooseMonth(dialog, year, month) {
    await dialog.getByRole('combobox', { name: 'Elegir el año' }).click();
    await page.getByRole('option', { name: String(year), exact: true }).click();
    await dialog.getByRole('combobox', { name: 'Elegir el mes' }).click();
    await page.getByRole('option', { name: month, exact: true }).click();
  }
  try {
    const root = await request('/auth/login', null, { email: configuration.PlatformAdmin__Email, password: configuration.PlatformAdmin__Password }, 'POST', 'peten');
    assert.equal(root.status, 200);
    const created = await request('/platform/tenants', root.result.accessToken, { code, name: 'Sede QA inscripción', administratorName: 'Admin QA', administratorEmail: email, administratorPassword: password }, 'POST', 'peten');
    assert.equal(created.status, 200); tenantCreated = true;
    await page.goto(base + '/acceso');
    await page.getByLabel('Código de sede').fill(code);
    await page.getByLabel('Correo electrónico').fill(email);
    await page.getByLabel('Contraseña', { exact: true }).fill(password);
    await page.getByRole('button', { name: /Ingresar al sistema/ }).click();
    await page.waitForURL(url => url.pathname === '/');
    await page.goto(base + '/personas/alumnos');
    await page.getByRole('button', { name: /Inscribir alumno/ }).click();
    let dialog = page.getByRole('dialog', { name: 'Inscribir alumno', exact: true });
    const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jhAAAAABJRU5ErkJggg==', 'base64');
    await dialog.locator('input[type=file]').setInputFiles({ name: 'perfil-qa.png', mimeType: 'image/png', buffer: png });
    await dialog.getByLabel('Nombre completo', { exact: true }).fill('Alumno QA inscripción');
    await dialog.getByLabel('Fecha de nacimiento', { exact: false }).first().fill('2001-07-16');
    await dialog.getByLabel('Carné universitario').fill(`1690-23-${String(Date.now()).slice(-5)}`);
    await dialog.getByLabel('DPI', { exact: true }).fill('3307445961712');
    assert.equal(await dialog.getByLabel('DPI', { exact: true }).inputValue(), '3307 44596 1712');
    await dialog.getByLabel('Correo electrónico', { exact: false }).fill(`alumno-${email}`);
    await dialog.getByRole('button', { name: 'Continuar', exact: true }).click();
    await dialog.getByLabel('Dirección de residencia').fill('Dirección QA');
    await dialog.getByLabel('Teléfono móvil').fill('56857965');
    await dialog.getByRole('button', { name: 'Continuar', exact: true }).click();
    assert.match(await dialog.getByRole('combobox', { name: /Registro inicial/ }).innerText(), /Presentada/);
    assert.equal(await dialog.getByLabel('Lugar asignado').count(), 0);
    await dialog.getByText('Sede QA inscripción', { exact: true }).waitFor();
    await dialog.getByRole('button', { name: 'Seleccionar hora de inicio' }).click();
    let time = page.getByRole('dialog', { name: 'Seleccionar Hora de inicio' });
    await time.locator('.time-picker-options').first().evaluate(element => { element.scrollTop = 300; });
    await page.waitForTimeout(100);
    assert.equal(await time.count(), 1);
    await time.getByRole('button', { name: '08', exact: true }).click();
    await time.getByRole('button', { name: '30', exact: true }).click();
    await dialog.getByRole('textbox', { name: 'Hora de finalización' }).fill('12:00');
    await dialog.getByRole('button', { name: 'Período de práctica', exact: true }).click();
    const range = page.getByRole('dialog', { name: 'Seleccionar Período de práctica' });
    await chooseMonth(range, 2026, 'octubre');
    await range.getByRole('button', { name: /15 de octubre de 2026/ }).click();
    await chooseMonth(range, 2027, 'abril');
    await range.getByRole('button', { name: /20 de abril de 2027/ }).click();
    await range.getByRole('button', { name: 'Aplicar rango' }).click();
    steps.push('Hora: scroll mantiene foco; rango: salto directo mes/año conserva inicio');
    await page.screenshot({ path: path.join(artifacts, 'practica.png'), fullPage: true });
    await dialog.getByRole('button', { name: 'Continuar', exact: true }).click();
    assert.equal(await dialog.getByRole('button', { name: /^Escanear / }).count(), 9);
    await dialog.getByRole('button', { name: /^Escanear Solicitud/ }).click();
    const scannerReady = await fetch('http://127.0.0.1:17654/health').then(response => response.ok).catch(() => false);
    if (scannerReady) {
      await dialog.getByRole('button', { name: 'Capturar documento' }).waitFor();
      assert.equal(await dialog.getByRole('button', { name: 'Capturar documento' }).isEnabled(), true);
      steps.push('Agente NAPS2 real: descubrimiento de dispositivos desde el navegador');
    } else await dialog.getByRole('alert').filter({ hasText: /escáner local/ }).waitFor();
    await dialog.getByRole('button', { name: 'Cancelar escaneo' }).click();
    const pdf = await PDFDocument.create(); pdf.addPage([300, 400]); const bytes = Buffer.from(await pdf.save());
    await dialog.locator('input[type=file]').first().setInputFiles({ name: 'solicitud-qa.pdf', mimeType: 'application/pdf', buffer: bytes });
    await dialog.getByRole('button', { name: 'Continuar', exact: true }).click();
    await dialog.getByLabel('Contraseña temporal', { exact: true }).fill(password);
    await dialog.getByLabel('Confirmar contraseña', { exact: true }).fill(password);
    await dialog.getByRole('button', { name: /Confirmar inscripción|Inscribir alumno|Crear alumno/ }).click();
    await page.waitForURL(url => /\/personas\/alumnos\/[^/]+$/.test(url.pathname), { timeout: 60000 });
    const id = new URL(page.url()).pathname.split('/').pop();
    const session = await page.evaluate(() => JSON.parse(sessionStorage.getItem('bufete_umg_session')));
    let profile = (await request(`/students/${id}/profile`, session.accessToken, null, 'GET')).result;
    assert.equal(profile.enrollments[0].status, 'Submitted');
    assert.equal(profile.enrollments[0].siteName, 'Sede QA inscripción');
    assert.equal(profile.enrollments[0].startDate, '2026-10-15');
    assert.equal(profile.enrollments[0].endDate, '2027-04-20');
    assert.ok(profile.student.photoDocumentId);
    await page.waitForFunction(() => Array.from(document.images).some(image => image.src.startsWith('blob:') && image.naturalWidth > 0));
    const requirement = profile.enrollments[0].requirements.find(item => item.documentId);
    assert.ok(requirement);
    const blockedApproval = await request(`/students/enrollments/${profile.enrollments[0].id}/status`, session.accessToken, { status: 'Approved', resolutionNotes: 'No debe aprobar sin evidencia' }, 'PUT');
    assert.equal(blockedApproval.status, 409);
    const download = await fetch(`${api}/documents/${requirement.documentId}/content`, { headers: { Authorization: `Bearer ${session.accessToken}`, 'X-Sede-Code': code } });
    assert.equal(download.status, 200); assert.deepEqual(Buffer.from(await download.arrayBuffer()), bytes);
    steps.push('Alta real: alumno/cuenta/práctica + foto MinIO + PDF asociado y descargado idéntico');
    await page.reload();
    await page.getByRole('button', { name: 'Editar perfil', exact: true }).click();
    dialog = page.getByRole('dialog', { name: 'Editar datos del alumno' });
    await dialog.getByLabel('Días de práctica', { exact: true }).fill('Lunes y miércoles');
    await dialog.getByLabel('Dirección del lugar de práctica').fill('Oficina QA actualizada');
    await dialog.getByRole('button', { name: 'Guardar perfil', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' }); await page.reload();
    profile = (await request(`/students/${id}/profile`, session.accessToken, null, 'GET')).result;
    assert.equal(profile.enrollments[0].practiceDays, 'Lunes y miércoles');
    assert.equal(profile.enrollments[0].siteAddress, 'Oficina QA actualizada');
    await page.getByRole('button', { name: 'Editar perfil', exact: true }).click();
    dialog = page.getByRole('dialog', { name: 'Editar datos del alumno' });
    assert.equal(await dialog.getByLabel('Días de práctica').inputValue(), 'Lunes y miércoles');
    await dialog.getByLabel('Días de práctica').scrollIntoViewIfNeeded();
    await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('.modal-backdrop')).opacity) > 0.99 && Number(getComputedStyle(document.querySelector('.modal')).opacity) > 0.99);
    await page.screenshot({ path: path.join(artifacts, 'edicion.png'), fullPage: true });
    await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
    const practice = { ...profile.enrollments[0], enrollmentId: profile.enrollments[0].id, siteName: 'Cobán falsificado', practiceDays: 'Jueves' };
    let response = await request(`/students/${id}`, session.accessToken, { ...profile.student, practice }, 'PUT');
    assert.equal(response.status, 200);
    const refreshed = (await request(`/students/${id}/profile`, session.accessToken, null, 'GET')).result;
    assert.equal(refreshed.enrollments[0].siteName, 'Sede QA inscripción');
    response = await request(`/students/${id}`, session.accessToken, { ...refreshed.student, fullName: 'No debe persistir', practice: { ...practice, concurrencyToken: refreshed.enrollments[0].concurrencyToken, startTime: '15:00', endTime: '08:00' } }, 'PUT');
    assert.equal(response.status, 400);
    assert.equal((await request(`/students/${id}/profile`, session.accessToken, null, 'GET')).result.student.fullName, 'Alumno QA inscripción');
    response = await request(`/students/${id}`, session.accessToken, { ...refreshed.student, practice }, 'PUT');
    assert.equal(response.status, 409);
    response = await request(`/students/${id}/profile`, session.accessToken, null, 'GET', 'peten');
    assert.equal(response.status, 401);
    steps.push('Edición/refresco/reapertura; sede impuesta; rango inválido no guarda parcialmente; conflicto de concurrencia');
    const central = configuration.POSTGRES_DB || (configuration.ConnectionStrings__BufeteDb || '').match(/Database=([^;]+)/i)?.[1];
    assert.match(central, /^[a-zA-Z0-9_]+$/);
    const dbArgs = ['exec', 'bufete-juridico-umg-postgres-1', 'psql', '-U', configuration.POSTGRES_USER, '-At', '-d'];
    const database = execFileSync('docker', [...dbArgs, central, '-c', `SELECT "DatabaseName" FROM bufete.tenants WHERE "Code"='${code}';`], { encoding: 'utf8' }).trim();
    assert.match(database, /^bufete_t_[a-f0-9]{32}$/);
    const auditCount = Number(execFileSync('docker', [...dbArgs, database, '-c', `SELECT COUNT(*) FROM bufete.audit_logs WHERE "EntityId"='${profile.enrollments[0].id}' AND "Action"='Update';`], { encoding: 'utf8' }).trim());
    assert.ok(auditCount >= 2);
    steps.push('PostgreSQL: auditoría de práctica comprobada; aprobación sin requisitos bloqueada; token no reutilizable en otra sede');
    const roleResult = await request('/roles', session.accessToken, null, 'GET');
    const secretaryRole = roleResult.result.find(role => role.name === 'Secretaria');
    assert.ok(secretaryRole);
    const secretaryEmail = `secretaria-${email}`;
    response = await request('/users', session.accessToken, { username: secretaryEmail, email: secretaryEmail, fullName: 'Secretaria QA inscripción', password, participationStartDate: null, participationEndDate: null, roleIds: [secretaryRole.id], studentId: null });
    assert.equal(response.status, 201);
    await page.evaluate(() => sessionStorage.clear());
    await page.goto(base + '/acceso');
    await page.getByLabel('Código de sede').fill(code);
    await page.getByLabel('Correo electrónico').fill(secretaryEmail);
    await page.getByLabel('Contraseña', { exact: true }).fill(password);
    await page.getByRole('button', { name: /Ingresar al sistema/ }).click();
    await page.waitForURL(url => url.pathname === '/');
    await page.goto(base + `/personas/alumnos/${id}`);
    await page.getByRole('button', { name: 'Editar perfil', exact: true }).click();
    dialog = page.getByRole('dialog', { name: 'Editar datos del alumno' });
    await dialog.getByText('Sede QA inscripción', { exact: true }).waitFor();
    assert.equal(await dialog.getByLabel('Lugar asignado').count(), 0);
    await dialog.getByLabel('Días de práctica').fill('Martes y jueves');
    await dialog.getByRole('button', { name: 'Guardar perfil', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    await page.reload();
    await page.getByText('Martes y jueves', { exact: true }).waitFor();
    steps.push('Secretaría: edición persistente dentro de su sede, sin selector libre de otra sede');
    assert.deepEqual(pageErrors, []);
    assert.ok(failedRequests.every(request => request.url.startsWith('http://127.0.0.1:17654/') || request.error === 'net::ERR_ABORTED'));
    assert.ok(consoleErrors.every(message => message.includes('Failed to load resource')));
    fs.writeFileSync(path.join(artifacts, 'result.json'), JSON.stringify({ passed: true, steps, pageErrors, consoleErrors, failedRequests }, null, 2));
    console.log(JSON.stringify({ passed: true, steps, artifacts }));
  } catch (error) {
    await page.screenshot({ path: path.join(artifacts, 'failure.png'), fullPage: true }).catch(() => {});
    fs.writeFileSync(path.join(artifacts, 'result.json'), JSON.stringify({ passed: false, steps, error: error.message, pageErrors }, null, 2));
    throw error;
  } finally {
    await browser.close();
    if (tenantCreated && /^qa-student-\d+$/.test(code)) {
      const central = configuration.POSTGRES_DB || (configuration.ConnectionStrings__BufeteDb || '').match(/Database=([^;]+)/i)?.[1];
      if (!central || !/^[a-zA-Z0-9_]+$/.test(central)) throw new Error('Base central QA no resuelta.');
      const args = ['exec', 'bufete-juridico-umg-postgres-1', 'psql', '-U', configuration.POSTGRES_USER, '-d', central, '-At', '-c'];
      const database = execFileSync('docker', [...args, `SELECT "DatabaseName" FROM bufete.tenants WHERE "Code" = '${code}';`], { encoding: 'utf8' }).trim();
      if (!/^bufete_t_[a-f0-9]{32}$/.test(database)) throw new Error('Base QA no validada.');
      execFileSync('docker', ['compose', '--env-file', '.env', '-f', 'compose.yaml', 'run', '--rm', '--no-deps', '--entrypoint', '/bin/sh', 'minio-init', '-c', `mc alias set qa "$MINIO_ENDPOINT" "$MINIO_ROOT_USER" "$MINIO_ROOT_PASSWORD" >/dev/null && mc rm --recursive --force "qa/$MINIO_BUCKET/bufete/tenants/${code}/"`], { stdio: 'pipe' });
      execFileSync('docker', ['exec', 'bufete-juridico-umg-postgres-1', 'dropdb', '-U', configuration.POSTGRES_USER, '--force', database]);
      execFileSync('docker', [...args, `DELETE FROM bufete.tenants WHERE "Code" = '${code}' AND "DatabaseName" = '${database}';`]);
    }
  }
}
main().catch(error => { console.error(error.stack); process.exitCode = 1; });
